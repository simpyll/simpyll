import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('board inventory, discovery, URL history, and grid share one collection', async ({ page, isMobile }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/projects')
  await expect(page.getByRole('button', { name: 'Board', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.lab-column')).toHaveCount(5)
  await expect(page.locator('[data-stage=in-progress] [data-project]')).toHaveCount(2)
  await expect(page.locator('[data-stage=on-deck] [data-project]')).toHaveCount(2)
  await expect(page.locator('[data-stage=shipped] [data-project]')).toHaveCount(0)
  if (isMobile) await page.getByLabel('Viewing stage').selectOption('ideas')
  await page.getByRole('button', { name: 'Show 13 more ideas' }).click()
  await expect(page.locator('[data-stage=ideas] [data-project]')).toHaveCount(17)
  await page.getByLabel('Technology', {exact: true}).selectOption('typescript')
  await expect(page.getByRole('status')).toContainText('1 project')
  await page.getByRole('button', { name: 'Grid', exact: true }).click()
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(1)
  await page.getByLabel('Workflow stage').selectOption('ideas')
  await expect(page.getByText('No projects match.', {exact:false})).toBeVisible()
  await page.goBack()
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(22)
  await page.getByLabel('Lifecycle', {exact: true}).selectOption('active')
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(2)
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await page.getByLabel('Project type', {exact: true}).selectOption('Healthcare Education')
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(7)
  await page.getByLabel('Search projects').fill('waveform')
  await expect(page.locator('.lab-grid [data-project]')).toHaveCount(1)
  await expect(page.locator('.lab-grid h3')).toHaveText('Ventilator Waveform Explorer')
  expect(errors).toEqual([])
})

for (const theme of ['light','dark'] as const) test(`board ${theme}: accessibility, overflow, navigation stability, and visual evidence`, async ({ page, isMobile }, info) => {
  await page.emulateMedia({colorScheme: theme, reducedMotion:'reduce'})
  await page.goto('/projects')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.getByRole('heading', { name:'Projects.', exact:true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const nav = page.locator('.floating-nav')
  await expect(page.locator('.floating-header')).toHaveAttribute('data-nav-ready','true')
  const before = await nav.boundingBox()
  await page.evaluate(() => scrollBy(0,120))
  await expect.poll(async () => (await nav.boundingBox())!.y).toBeCloseTo(before!.y, 0)
  await page.locator('.theme-toggle').click()
  await expect.poll(async () => (await nav.boundingBox())!.y).toBeCloseTo(before!.y, 0)
  await page.locator('.theme-toggle').click()
  await page.evaluate(() => scrollTo(0,0))
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([])
  if (isMobile) {
    for (const id of ['ideas','on-deck','in-progress','shipped','archived']) {
      await page.getByLabel('Viewing stage').selectOption(id)
      await expect(page.locator(`[data-stage="${id}"]`)).toBeVisible()
    }
    await page.getByLabel('Viewing stage').selectOption('in-progress')
  } else {
    await page.locator('.lab-board').focus()
    await expect(page.locator('.lab-board')).toBeFocused()
    await page.locator('.lab-board').evaluate(el => el.scrollTo({left:0,behavior:'instant'}))
  }
  await page.locator('h1').click()
  await page.screenshot({path:info.outputPath(`board-${theme}.png`),fullPage:true})
  await page.getByRole('button',{name:'Grid',exact:true}).click()
  await page.screenshot({path:info.outputPath(`grid-${theme}.png`),fullPage:true})
  await page.getByLabel('Search projects').fill('clinical')
  await page.screenshot({path:info.outputPath(`filtered-${theme}.png`),fullPage:true})
  await page.getByLabel('Search projects').fill('zzzzzzzz')
  await page.screenshot({path:info.outputPath(`empty-${theme}.png`),fullPage:true})
})

test('projects prerender contains inventory and canonical without JavaScript',async ({browser})=>{
  const context=await browser.newContext({javaScriptEnabled:false})
  const page=await context.newPage()
  await page.goto('/projects')
  await expect(page.locator('[data-project=simpyll]')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Ventilator Waveform Explorer'})).toBeVisible()
  await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href','https://simpyll.com/projects')
  await context.close()
})

 test('direct query URL hydrates and preserves controls through keyboard view changes', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/projects?q=clinical&view=grid&stage=ideas')
  await expect(page.getByLabel('Search projects')).toHaveValue('clinical')
  await expect(page.getByLabel('Workflow stage', {exact:true})).toHaveValue('ideas')
  const gridIds = await page.locator('.lab-grid [data-project]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-project')))
  expect(new Set(gridIds).size).toBe(gridIds.length)
  const board=page.getByRole('button',{name:'Board',exact:true})
  await board.focus()
  await page.keyboard.press('Enter')
  await expect(board).toHaveAttribute('aria-pressed','true')
  await expect(page.getByLabel('Search projects')).toHaveValue('clinical')
  await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href','https://simpyll.com/projects')
  expect(errors).toEqual([])
 })
