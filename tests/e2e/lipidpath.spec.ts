import { expect, test, type Page } from '@playwright/test'
import { ready, scan, tabTo } from './helpers/accessibility'
async function choose(page:Page,label:string,value:string) {await page.getByLabel(label,{exact:true}).selectOption(value)}
async function coreProfile(page:Page) {
  await page.getByLabel('Age (years)',{exact:true}).fill('50')
  await choose(page,'Current reproductive context','none')
  for(const label of ['Established clinical ASCVD?','Diabetes?','History of untreated LDL-C ≥190 mg/dL?','Established CKD stage 3 or higher?','Living with HIV?','Complex care requiring individual review?']) await choose(page,label,'false')
  await choose(page,'Confirmed familial hypercholesterolemia','none')
  await choose(page,'Contraindications and drug interactions reviewed?','true')
}
test('guided primary-prevention result, trace, privacy and reset',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error'&&/hydration|hydrated|server.rendered|#418/i.test(m.text()))errors.push(m.text())})
  const calls:string[]=[];page.on('request',r=>calls.push(r.url()))
  await page.goto('/tools/lipidpath');await ready(page)
  await expect(page.getByRole('heading',{name:/LipidPath/})).toBeVisible()
  await coreProfile(page)
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Laboratory results',exact:true})).toBeFocused()
  await page.getByLabel('Current LDL-C (mg/dL)',{exact:true}).fill('120')
  await page.getByLabel('Total cholesterol (optional) (mg/dL)',{exact:true}).fill('220')
  await page.getByLabel('HDL-C (optional) (mg/dL)',{exact:true}).fill('50')
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await choose(page,'Current statin intensity','none')
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByLabel('10-year PREVENT-ASCVD risk (%)',{exact:true}).fill('5')
  await choose(page,'These results are from the official PREVENT-ASCVD outcome?','true')
  await page.getByRole('button',{name:'Review guideline results',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Guideline results',exact:true})).toBeFocused()
  await expect(page.getByText('Intermediate 10-year ASCVD risk:',{exact:true})).toBeVisible()
  await expect(page.getByText('below 100 mg/dL',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Pathway branch diagram'}).getByText('Triggered branch',{exact:true})).toHaveCount(1)
  await page.getByRole('region',{name:'Interactive decision pathway'}).locator('summary').filter({hasText:'Manual PREVENT-ASCVD result'}).click()
  await expect(page.getByText(/User-confirmed official ASCVD outcome/)).toBeVisible()
  await scan(page,info,'lipidpath-result')
  await expect(page).toHaveURL(/\/tools\/lipidpath$/)
  expect(calls.filter(url=>!url.startsWith('http://127.0.0.1:'))).toEqual([])
  const stored=await page.evaluate(()=>({...localStorage,...sessionStorage}))
  expect(Object.keys(stored).filter(key=>/lipid|patient|clinical|risk|ldl/i.test(key))).toEqual([])
  expect(errors).toEqual([])
  await page.screenshot({path:info.outputPath('lipidpath-results.png'),fullPage:true})
  await page.getByRole('button',{name:'Reset all inputs',exact:true}).click()
  await expect(page.getByLabel('Age (years)',{exact:true})).toHaveValue('')
  await page.reload();await ready(page)
  await expect(page.getByLabel('Age (years)',{exact:true})).toHaveValue('')
})
test('missing data and pregnancy stop unsupported treatment output',async({page})=>{
  await page.goto('/tools/lipidpath');await ready(page)
  await page.getByRole('button',{name:/Guideline results$/}).click()
  await expect(page.getByRole('heading',{name:'Missing information'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Lipid goals for discussion'})).toHaveCount(0)
  await page.getByRole('button',{name:/Profile$/}).click();await coreProfile(page)
  await choose(page,'Current reproductive context','pregnant')
  await page.getByRole('button',{name:/Laboratory results$/}).click()
  await page.getByLabel('Current LDL-C (mg/dL)',{exact:true}).fill('200')
  await page.getByRole('button',{name:/Guideline results$/}).click()
  await expect(page.getByText('Individualized evaluation required',{exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Lipid goals for discussion'})).toHaveCount(0)
})
test('keyboard, light theme, evidence explorer and responsive layout',async({page},info)=>{
  await page.addInitScript(()=>localStorage.setItem('simpyll-theme','light'))
  await page.goto('/tools/lipidpath');await ready(page)
  await tabTo(page,page.getByRole('button',{name:'Guideline explorer',exact:true}))
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button',{name:'Guideline explorer',exact:true})).toHaveAttribute('aria-pressed','true')
  const rule=page.locator('#evidence-very-high summary');await rule.scrollIntoViewIfNeeded();await rule.click()
  await expect(page.locator('#evidence-very-high')).toContainText('COR 1 · LOE A')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await scan(page,info,'lipidpath-explorer')
  await page.screenshot({path:info.outputPath('lipidpath-explorer.png'),fullPage:true})
})
