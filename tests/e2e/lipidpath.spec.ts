import { expect, test, type Page } from '@playwright/test'
import { ready, scan, tabTo } from './helpers/accessibility'
async function choose(page:Page,label:string,value:string) {await page.getByLabel(label,{exact:true}).selectOption(value)}
async function coreProfile(page:Page) {
  await page.getByLabel('Age (years)',{exact:true}).fill('50')
  await page.getByText('Additional health and safety details',{exact:true}).click()
  await choose(page,'Current reproductive context','none')
  for(const label of ['Established clinical ASCVD?','Diabetes?','History of untreated LDL-C ≥190 mg/dL?','Established CKD stage 3 or higher?','Living with HIV?','Complex care requiring individual review?']) await choose(page,label,'false')
  await choose(page,'Confirmed familial hypercholesterolemia','none')
  await choose(page,'Contraindications and drug interactions reviewed?','true')
}
