test('decimal entry and unit changes preserve the entered value',async({page})=>{
  await page.goto('/tools/lipidpath');await ready(page)
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByLabel('Cholesterol and triglyceride input units').selectOption('mmol/L')
  const input=page.getByLabel('Current LDL-C (mmol/L)',{exact:true})
  await input.pressSequentially('4.90')
  await expect(input).toHaveValue('4.90')
  await page.getByLabel('Cholesterol and triglyceride input units').selectOption('mg/dL')
  const value=Number(await page.getByLabel('Current LDL-C (mg/dL)',{exact:true}).inputValue())
  expect(value).toBeGreaterThan(189)
  expect(value).toBeLessThan(190)
  await page.getByRole('button',{name:'See results so far',exact:true}).click()
  await expect(page.getByText(/markedly elevated result/)).toHaveCount(0)
})

